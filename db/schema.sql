create table if not exists job_seekers (
    user_id bigint primary key,
    username text,
    sphere text not null,
    schedule text not null,
    salary_min integer,
    salary_max integer,
    about text not null,
    active boolean not null default true,
    vip_until timestamptz,
    referred_by bigint,
    found_work boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists job_vacancies (
    id bigint generated by default as identity primary key,
    employer_id bigint not null,
    employer_username text,
    referred_by bigint,
    title text not null,
    sphere text not null,
    schedule text not null,
    salary_min integer,
    salary_max integer,
    contacts text not null,
    description text not null,
    status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'closed')),
    closed_via_bot boolean not null default false,
    moderation_reason text,
    channel_message_id bigint,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists job_notifications (
    id bigint generated by default as identity primary key,
    vacancy_id bigint not null references job_vacancies(id) on delete cascade,
    seeker_id bigint not null references job_seekers(user_id) on delete cascade,
    sent_at timestamptz not null default now(),
    reacted text not null default 'none' check (reacted in ('like', 'dislike', 'none', 'complaint')),
    unique (vacancy_id, seeker_id)
);

create table if not exists payments (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    type text not null check (type in ('stars', 'manual')),
    amount integer not null,
    feature text not null check (feature in ('unlimited_vacancies', 'pin_vacancy', 'urgent_broadcast', 'vip_seeker')),
    status text not null default 'pending' check (status in ('pending', 'paid', 'rejected')),
    vacancy_id bigint references job_vacancies(id) on delete set null,
    telegram_payment_charge_id text,
    provider_payment_charge_id text,
    created_at timestamptz not null default now(),
    paid_at timestamptz,
    expires_at timestamptz
);

create table if not exists usage_limits (
    user_id bigint primary key,
    vacancies_this_month integer not null default 0,
    notifications_today integer not null default 0,
    urgent_broadcasts_this_month integer not null default 0,
    last_reset_month text not null,
    last_reset_day text not null,
    updated_at timestamptz not null default now()
);

create table if not exists referrals (
    referrer_id bigint not null,
    referred_id bigint primary key,
    created_at timestamptz not null default now(),
    bonus_vip_granted boolean not null default false
);

create table if not exists scheduled_unpins (
    id bigint generated by default as identity primary key,
    vacancy_id bigint not null references job_vacancies(id) on delete cascade,
    channel_message_id bigint not null,
    unpin_at timestamptz not null,
    status text not null default 'scheduled' check (status in ('scheduled', 'done', 'failed')),
    created_at timestamptz not null default now()
);

alter table job_seekers add column if not exists referred_by bigint;
alter table job_seekers add column if not exists found_work boolean not null default false;
alter table job_vacancies add column if not exists referred_by bigint;
alter table job_vacancies add column if not exists closed_via_bot boolean not null default false;

create index if not exists idx_job_seekers_matching
    on job_seekers (sphere, schedule)
    where active = true;

create index if not exists idx_job_vacancies_status
    on job_vacancies (status, created_at desc);

create index if not exists idx_payments_user_feature_status
    on payments (user_id, feature, status, created_at desc);

create index if not exists idx_job_notifications_seeker_sent
    on job_notifications (seeker_id, sent_at desc);

create index if not exists idx_scheduled_unpins_due
    on scheduled_unpins (status, unpin_at);

create table if not exists scheduled_tasks (
    id bigint generated by default as identity primary key,
    task_type text not null,
    payload jsonb not null default '{}'::jsonb,
    run_at timestamptz not null,
    status text not null default 'scheduled' check (status in ('scheduled', 'done', 'failed')),
    created_at timestamptz not null default now()
);

create index if not exists idx_scheduled_tasks_due
    on scheduled_tasks (status, run_at);

